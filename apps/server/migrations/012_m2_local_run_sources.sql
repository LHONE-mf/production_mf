-- Additive typed references to slurry batch and electrode coating run
-- snapshots. The values are unverified user assertions, not verified output,
-- quality release, stock posting or equipment control.
BEGIN;
ALTER TABLE production_local_journal_links
  ADD COLUMN source_kind text NOT NULL DEFAULT 'journal'
    CHECK (source_kind IN ('journal','mix_batch','coat_run')),
  ADD COLUMN source_measure_kind text
    CHECK (source_measure_kind IN ('dry_solids_kg','coated_side_a_m')),
  ADD COLUMN source_measure_value numeric(18,6)
    CHECK (source_measure_value > 0);

ALTER TABLE production_local_journal_links
  ADD CONSTRAINT production_local_source_measure_pair CHECK (
    (source_measure_kind IS NULL AND source_measure_value IS NULL)
    OR (source_measure_kind IS NOT NULL AND source_measure_value IS NOT NULL
      AND ((source_kind='mix_batch' AND source_stage='slurry'
          AND source_measure_kind='dry_solids_kg')
        OR (source_kind='coat_run' AND source_stage='coating'
          AND source_measure_kind='coated_side_a_m')))
  ),
  ADD CONSTRAINT production_local_source_stage_kind CHECK (
    source_kind='journal'
    OR (source_kind='mix_batch' AND source_stage='slurry')
    OR (source_kind='coat_run' AND source_stage='coating')
  );
-- PostgreSQL truncates autogenerated names at 63 characters. Locate the
-- original UNIQUE constraint via catalog instead of guessing its name.
DO $$
DECLARE old_name text;
BEGIN
  SELECT conname INTO old_name FROM pg_constraint
    WHERE conrelid='production_local_journal_links'::regclass
      AND contype='u' AND conname <> 'production_local_source_identity';
  IF old_name IS NOT NULL THEN
    EXECUTE format('ALTER TABLE production_local_journal_links DROP CONSTRAINT %I',old_name);
  END IF;
END
$$;
ALTER TABLE production_local_journal_links
  ADD CONSTRAINT production_local_source_identity
  UNIQUE(organization_id,source_kind,source_entry_id);
COMMIT;
